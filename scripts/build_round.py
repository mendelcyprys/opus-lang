#!/usr/bin/env python3
"""Build a practice round: languages/<lang>/tools/round.json  ->  the ITEMS / MODEL blocks of <lang>-practice.html.

Usage:
  python3 scripts/build_round.py <lang>            # round.json -> page (validates first)
  python3 scripts/build_round.py <lang> --extract  # page -> round.json (seed from the items currently in the page)

round.json = {"items": [ ... ]}; per item:
  mc    {"t":"mc","p":prompt,"opts":[correct, wrong, wrong, wrong],"why":"...","tag":"..."}   (correct option FIRST; the page shuffles)
  type  {"t":"type","p":prompt,"a":[accepted answers],"model":"answer shown after checking","tag":"..."}
  build {"t":"build","p":prompt,"words":[in correct order],"alt":[optional alternative strings],"model":"...","tag":"..."}
Order: put mc first, then build, then type (the page shows them in file order).
Then publish with the Artifact tool: same file path (keeps the URL), capabilities {"sample":{},"comments":{}}.
"""
import json, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BLOCK = re.compile(r"const ITEMS = \[.*?\n\];\n.*?const MODEL = .*?\n", re.S)


def paths(lang):
    t = ROOT / "languages" / lang / "tools"
    pages = sorted(t.glob("*-practice.html"))
    if not pages:
        sys.exit(f"No practice page in {t}")
    return t / "round.json", pages[0]


def validate(items):
    errs = []
    for i, it in enumerate(items, 1):
        t = it.get("t")
        if t not in ("mc", "type", "build"):
            errs.append(f"{i}: unknown type {t!r}")
        elif not it.get("p") or not it.get("tag"):
            errs.append(f"{i}: needs p and tag")
        elif t == "mc" and (len(it.get("opts", [])) < 2 or len(set(it["opts"])) != len(it["opts"])):
            errs.append(f"{i}: mc needs ≥2 distinct opts (correct first)")
        elif t == "type" and not it.get("a"):
            errs.append(f"{i}: type needs a (accepted answers)")
        elif t == "build" and len(it.get("words", [])) < 2:
            errs.append(f"{i}: build needs words")
    return errs


def js(items):
    lines = []
    for it in items:
        o = {k: v for k, v in it.items() if k != "model"}
        if o["t"] == "mc":
            o["a"] = 0
            o = {k: o[k] for k in ("t", "p", "opts", "a", "why", "tag") if k in o}
        lines.append("  " + json.dumps(o, ensure_ascii=False) + ",")
    model = {i: it["model"] for i, it in enumerate(items) if it.get("model")}
    mjs = "{" + ",".join(f"{i}:{json.dumps(m, ensure_ascii=False)}" for i, m in model.items()) + "}"
    return ("const ITEMS = [\n" + "\n".join(lines) + "\n];\n"
            "// shown after checking, keyed by index in ITEMS (generated by scripts/build_round.py from round.json)\n"
            f"const MODEL = {mjs};\n")


def build(lang):
    rj, page = paths(lang)
    items = json.loads(rj.read_text(encoding="utf-8"))["items"]
    errs = validate(items)
    if errs:
        sys.exit("round.json problems:\n  " + "\n  ".join(errs))
    text = page.read_text(encoding="utf-8")
    new, n = BLOCK.subn(lambda m: js(items), text, count=1)
    if n != 1:
        sys.exit("Could not find the ITEMS/MODEL block in " + page.name)
    page.write_text(new, encoding="utf-8")
    k = {t: sum(1 for i in items if i["t"] == t) for t in ("mc", "build", "type")}
    print(f"{page.relative_to(ROOT)}: {len(items)} items ({k['mc']} mc, {k['build']} build, {k['type']} typed)")


def extract(lang):
    rj, page = paths(lang)
    m = BLOCK.search(page.read_text(encoding="utf-8"))
    if not m:
        sys.exit("No ITEMS/MODEL block found")
    code = m.group(0) + "\nconsole.log(JSON.stringify({ITEMS, MODEL}));"
    out = subprocess.run(["node", "-e", code], capture_output=True, text=True)
    if out.returncode:
        sys.exit(out.stderr)
    d = json.loads(out.stdout)
    items = []
    for i, it in enumerate(d["ITEMS"]):
        it = dict(it)
        if it["t"] == "mc":
            k = it.pop("a", 0)
            it["opts"] = [it["opts"][k]] + [o for j, o in enumerate(it["opts"]) if j != k]   # correct option first
        if str(i) in d["MODEL"]:
            it["model"] = d["MODEL"][str(i)]
        items.append(it)
    rj.write_text(json.dumps({"items": items}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {rj.relative_to(ROOT)} ({len(items)} items)")


def main():
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    (extract if "--extract" in a else build)(a[0].lower())


if __name__ == "__main__":
    main()
